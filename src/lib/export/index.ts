import { FullEventPlan } from "../types";
import { formatINR } from "../engines/budget";
import { generateIcsCalendar } from "../engines/timeline";

export function generateMarkdownPlan(plan: FullEventPlan): string {
  const { event, budget, tasks, vendors, ideas } = plan;

  const totalEstimated = budget.reduce((acc, i) => acc + (i.estimatedAmount || 0), 0);
  const totalActual = budget.reduce((acc, i) => acc + (i.actualAmount || 0), 0);

  let md = `# ${event.title}\n`;
  md += `*Event Type:* ${event.eventType.toUpperCase()} | *City:* ${event.city} | *Date:* ${event.eventDate}\n`;
  md += `*Expected Guests:* ${event.guestCount} | *Total Budget:* ${formatINR(event.totalBudget)}\n\n`;

  if (event.notes) {
    md += `> **Notes:** ${event.notes}\n\n`;
  }

  md += `## 1. Budget Breakdown\n\n`;
  md += `| Category | Item | Estimated | Actual | Status |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- |\n`;
  budget.forEach((b) => {
    md += `| ${b.category} | ${b.name} | ${formatINR(b.estimatedAmount)} | ${formatINR(b.actualAmount)} | ${b.status || "planned"} |\n`;
  });
  md += `| **TOTAL** | | **${formatINR(totalEstimated)}** | **${formatINR(totalActual)}** | |\n\n`;

  md += `## 2. Event Timeline & Milestones\n\n`;
  md += `| Due Date | Priority | Task | Category | Status |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- |\n`;
  tasks.forEach((t) => {
    md += `| ${t.dueDate} | ${t.priority.toUpperCase()} | ${t.title} | ${t.category} | ${t.status} |\n`;
  });
  md += `\n`;

  md += `## 3. Vendor Coordination Checklist\n\n`;
  md += `| Category | Vendor Name | Contact | Est. Quote | Final Quote | Status |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- | :--- |\n`;
  vendors.forEach((v) => {
    md += `| ${v.category} | ${v.businessName} | ${v.phone || "N/A"} | ${formatINR(v.estimatedQuote)} | ${formatINR(v.finalQuote)} | ${v.status} |\n`;
  });
  md += `\n`;

  if (ideas && ideas.length > 0) {
    md += `## 4. Personalized Ideas & Themes\n\n`;
    ideas.forEach((idea) => {
      md += `### ${idea.title} [${idea.section.toUpperCase()} - ${idea.costTier}]\n`;
      md += `${idea.description}\n\n`;
    });
  }

  md += `---\n*Generated by UtsavMate AI — Every celebration. One smart plan.*`;
  return md;
}

export function generateBudgetCsv(plan: FullEventPlan): string {
  const sanitize = (val: string | number) => `"${String(val).replace(/"/g, '""')}"`;
  const headers = ["Category", "Item Name", "Estimated Amount (INR)", "Actual Amount (INR)", "Status", "Notes"];

  const rows = plan.budget.map((b) => [
    sanitize(b.category),
    sanitize(b.name),
    b.estimatedAmount,
    b.actualAmount,
    sanitize(b.status || "planned"),
    sanitize(b.notes || ""),
  ]);

  return [headers.join(","), ...rows.map((r) => r.join(","))].join("\n");
}

export function generateVendorCsv(plan: FullEventPlan): string {
  const sanitize = (val: string | number) => `"${String(val).replace(/"/g, '""')}"`;
  const headers = [
    "Category",
    "Business Name",
    "Contact Person",
    "Phone",
    "Email",
    "Estimated Quote (INR)",
    "Final Quote (INR)",
    "Status",
    "Notes",
  ];

  const rows = plan.vendors.map((v) => [
    sanitize(v.category),
    sanitize(v.businessName),
    sanitize(v.contactPerson || ""),
    sanitize(v.phone || ""),
    sanitize(v.email || ""),
    v.estimatedQuote,
    v.finalQuote,
    sanitize(v.status),
    sanitize(v.notes || ""),
  ]);

  return [headers.join(","), ...rows.map((r) => r.join(","))].join("\n");
}

